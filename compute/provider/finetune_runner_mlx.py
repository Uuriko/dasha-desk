#!/usr/bin/env python3
"""Dasha Compute fine-tune engine backend: `mlx` (Apple Silicon, MLX LM).

Implements the engine-backend interface documented in finetune_runner.py:

    ENGINE_ID = "mlx"
    generate_config(spec, ctx) -> {"command", "config_path", "config_text"}
    run(config, ctx) -> dict   # terminal result incl. "engine": "mlx"
    report_telemetry(coordinator, token, job_id, update) -> dict
    doctor() -> int

The backend NEVER executes client-supplied code, shell, or YAML. It only
ever runs one fixed command — `python -m mlx_lm lora -c <job.yaml>` — where
job.yaml is generated deterministically by generate_config() from the
validated spec. Requires mlx-lm 0.31.x and huggingface_hub.
"""

import json
import os
import re
import signal
import subprocess
import sys
import threading
import time

import finetune_runner as core

ENGINE_ID = "mlx"
MLX_LM_MIN_VERSION = (0, 31)

# Provider-side base-model allowlist (defense in depth; the server's MODELS +
# license gate is authoritative). QLoRA is automatic on these 4-bit bases.
BASE_MODELS = {
    "qwen3-1.7b": {"repo": "mlx-community/Qwen3-1.7B-4bit", "size_tier": "1b", "min_memory_gb": 4},
    "qwen3-4b": {"repo": "mlx-community/Qwen3-4B-4bit", "size_tier": "3b", "min_memory_gb": 6},
    "qwen3-8b": {"repo": "mlx-community/Qwen3-8B-4bit", "size_tier": "8b", "min_memory_gb": 10},
    "gemma3-4b": {"repo": "mlx-community/gemma-3-4b-it-4bit", "size_tier": "3b", "min_memory_gb": 6},
}

# Fixed fields the client cannot change (spec §"Deterministic config generation").
FIXED_YAML_FIELDS = {
    "train": True,
    "grad_checkpoint": True,
    "mask_prompt": True,
    "optimizer": "adamw",
    "steps_per_report": 10,
    "steps_per_eval": 100,
    "report_to": "coordinator",
}

# Deterministic key order for the emitted YAML.
YAML_KEY_ORDER = (
    "model", "train", "data", "fine_tune_type", "num_layers", "batch_size",
    "iters", "val_batches", "learning_rate", "max_seq_length", "seed",
    "grad_checkpoint", "mask_prompt", "optimizer", "steps_per_report",
    "steps_per_eval", "save_every", "adapter_path", "resume_adapter_file",
    "report_to",
)


def _yaml_scalar(value):
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    return json.dumps(str(value))  # JSON strings are valid YAML scalars


def spec_to_yaml(spec, *, base_repo, train_path, valid_path, adapter_path, resume_adapter_file=None):
    """Generate the mlx-lm job.yaml deterministically from a sanitized spec.

    The ONLY YAML this backend will ever execute. `spec` must already have
    passed core.sanitize_spec(); client-supplied YAML is never accepted.
    """
    values = {
        "model": base_repo,
        "train": True,
        "data": os.path.dirname(train_path),
        "fine_tune_type": spec["finetune_type"],
        "num_layers": spec["lora_layers"],
        "batch_size": spec["batch_size"],
        "iters": spec["iters"],
        "val_batches": 25,
        "learning_rate": spec["learning_rate"],
        "max_seq_length": spec["max_seq_length"],
        "seed": spec["seed"],
        "grad_checkpoint": True,
        "mask_prompt": True,
        "optimizer": "adamw",
        "steps_per_report": 10,
        "steps_per_eval": 100,
        "save_every": spec["save_every"],
        "adapter_path": adapter_path,
        "resume_adapter_file": resume_adapter_file,
        "report_to": "coordinator",
    }
    lines = ["# generated by dasha-compute finetune_runner_mlx — do not hand-edit"]
    for key in YAML_KEY_ORDER:
        lines.append(f"{key}: {_yaml_scalar(values[key])}")
    lines.append(f"lora_rank: {_yaml_scalar(spec['lora_rank'])}")
    lines.append(f"train_file: {_yaml_scalar(os.path.basename(train_path))}")
    lines.append(f"valid_file: {_yaml_scalar(os.path.basename(valid_path))}")
    return "\n".join(lines) + "\n"


def build_train_command(config_path):
    """The one and only command this backend executes.

    config_path must point at a job.yaml produced by generate_config(); the
    path itself is derived from the job working directory, never from
    client input.
    """
    return [sys.executable, "-m", "mlx_lm", "lora", "-c", config_path]


def check_mlx_lm():
    try:
        import mlx_lm  # noqa: F401
        from importlib.metadata import version
        parts = tuple(int(p) for p in version("mlx-lm").split(".")[:2])
        return parts >= MLX_LM_MIN_VERSION, version("mlx-lm")
    except Exception as error:
        return False, str(error)


def ensure_base_model(repo):
    """Download/cache the allowlisted 4-bit base once. Returns local path."""
    from huggingface_hub import snapshot_download
    return snapshot_download(repo_id=repo, cache_dir=core.model_cache_dir())


def report_telemetry(coordinator, token, job_id, update):
    return core.report_progress(coordinator, token, job_id, update)


def generate_config(spec, ctx):
    """Build this backend's config from the sanitized spec; write job.yaml."""
    base = BASE_MODELS[spec["base_model"]]
    config_path = os.path.join(ctx.workdir, "job.yaml")
    config_text = spec_to_yaml(
        spec, base_repo=base["repo"], train_path=ctx.train_path,
        valid_path=ctx.valid_path, adapter_path=ctx.adapter_dir,
        resume_adapter_file=ctx.resume_dir,
    )
    with open(config_path, "w", encoding="utf-8") as handle:
        handle.write(config_text)
    return {"command": build_train_command(config_path),
            "config_path": config_path, "config_text": config_text,
            "spec": spec, "base_model": spec["base_model"]}


