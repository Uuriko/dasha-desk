def _rss_mb(pid):
    try:
        out = subprocess.run(["ps", "-o", "rss=", "-p", str(pid)],
                             capture_output=True, text=True, timeout=5).stdout.strip()
        return int(out) // 1024
    except Exception:
        return 0


class Watchdog:
    """Kills the trainer on wall-clock or memory overrun."""

    def __init__(self, process, max_wall_seconds, max_rss_mb):
        self.process = process
        self.deadline = time.monotonic() + max_wall_seconds
        self.max_rss_mb = max_rss_mb
        self.tripped = None
        self._stop = threading.Event()
        self._thread = threading.Thread(target=self._watch, daemon=True)

    def start(self):
        self._thread.start()

    def stop(self):
        self._stop.set()
        self._thread.join(5)

    def _watch(self):
        while not self._stop.wait(15):
            if self.process.poll() is not None:
                return
            if time.monotonic() > self.deadline:
                self.tripped = "wall_clock_exceeded"
                self.process.kill()
                return
            if self.max_rss_mb and _rss_mb(self.process.pid) > self.max_rss_mb:
                self.tripped = "memory_exceeded"
                self.process.kill()
                return


LOSS_LINE_RE = re.compile(r"[Ii]ter(?:ation)?\s+(\d+).*?[Ll]oss\s+([0-9.]+)")


def _parse_loss_line(line):
    match = LOSS_LINE_RE.search(line)
    if match:
        return int(match.group(1)), float(match.group(2))
    return None


def run(config, ctx):
    """Run the fixed trainer command; stream telemetry; return the result."""
    ok, mlx_version = check_mlx_lm()
    if not ok:
        raise RuntimeError(f"mlx-lm 0.31.x required: {mlx_version}")
    ensure_base_model(BASE_MODELS[config["base_model"]]["repo"])
    command = config["command"]
    process = subprocess.Popen(command, cwd=ctx.workdir, stdout=subprocess.PIPE,
                               stderr=subprocess.STDOUT, text=True, bufsize=1)
    watchdog = Watchdog(process, ctx.max_wall_seconds, ctx.max_rss_mb)
    watchdog.start()
    train_loss, iters_done = [], 0
    cancelled = threading.Event()

    def _on_signal(_signum, _frame):
        cancelled.set()
        try:
            process.terminate()
        except Exception:
            pass

    old_handlers = {s: signal.signal(s, _on_signal) for s in (signal.SIGINT, signal.SIGTERM)}
    try:
        for line in process.stdout:
            parsed = _parse_loss_line(line)
            if parsed:
                iters_done, loss = parsed
                train_loss.append(loss)
                update = {"iters_done": iters_done, "train_loss": loss}
                if ctx.progress_callback:
                    ctx.progress_callback(update)
                else:
                    report_telemetry(ctx.coordinator, ctx.token, ctx.job_id, update)
        process.wait()
    finally:
        for sig, handler in old_handlers.items():
            signal.signal(sig, handler)
        watchdog.stop()

    base_result = {"job_id": ctx.job_id, "engine": ENGINE_ID, "iters_done": iters_done,
                   "spec_hash": core.spec_hash(config["spec"])}
    if watchdog.tripped == "memory_exceeded":
        raise RuntimeError("trainer killed: memory cap exceeded")
    if watchdog.tripped == "wall_clock_exceeded" or cancelled.is_set():
        checkpoint_ref = None
        try:
            checkpoint_ref = core.upload_adapter_dir(ctx.coordinator, ctx.token, ctx.job_id, ctx.adapter_dir)
        except Exception:
            pass
        return {**base_result, "status": "preempted", "checkpoint_ref": checkpoint_ref}
    if process.returncode != 0:
        return {**base_result, "status": "failed",
                "error": f"mlx_lm exited with code {process.returncode}"}
    adapter_ref = core.upload_adapter_dir(ctx.coordinator, ctx.token, ctx.job_id, ctx.adapter_dir)
    return {**base_result, "status": "complete", "train_loss": train_loss,
            "adapter_ref": adapter_ref}


def doctor():
    failures = 0
    ok, detail = check_mlx_lm()
    print(f"mlx       {'ok · ' + detail if ok else 'failed · ' + detail}")
    failures += 0 if ok else 1
    print(f"mlx       bases: {', '.join(BASE_MODELS)}")
    return failures
